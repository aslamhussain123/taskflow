import { Request, Response } from 'express';
import { generateTaskFromPrompt } from '../services/ai.service';
import prisma from '../config/database';
import { asyncHandler } from '../utils/asyncHandler';
import { sendSuccess, sendError } from '../utils/apiResponse';

export const generateTask = asyncHandler(async (req: Request, res: Response) => {
  const { prompt } = req.body;
  const userId = (req as any).user.id;

  if (!prompt) {
    return sendError(res, 'Prompt is required', 400);
  }

  let aiData;

  try {
    aiData = await generateTaskFromPrompt(prompt);
  } catch (error: any) {
    const status = error?.status;
    const code = error?.code;
    const message = typeof error?.message === 'string' ? error.message : 'Unknown provider error';
    console.error('[AI] request failed:', { status, code, message });

    if (status === 402) {
      return sendError(
        res,
        'The configured Ollama cloud model requires usage credits. Use the local Ollama service in Docker or add credits to your Ollama account.',
        402
      );
    }

    if (status === 401 || status === 403) {
      return sendError(res, 'Ollama rejected the API key or model access. Check the Ollama account and model permissions.', 502);
    }

    if (status === 404) {
      return sendError(res, 'The configured Ollama model was not found. Check OLLAMA_MODEL and ensure the model has been pulled.', 502);
    }

    if (error?.status === 429) {
      return sendError(
        res,
        'Too many AI requests. Please try again later.',
        429
      );
    }

    return sendError(
      res,
      'Failed to generate task using AI. Please try again.',
      502
    );
  }

  const parsedDueDate = aiData.dueDate ? new Date(aiData.dueDate) : null;

  const dueDate =
    parsedDueDate && !Number.isNaN(parsedDueDate.getTime())
      ? parsedDueDate
      : null;

  const task = await prisma.task.create({
    data: {
      title: aiData.title,
      description: aiData.description,
      priority: aiData.priority,
      status: 'BACKLOG',
      dueDate,
      userId,
    },
  });

  return sendSuccess(res, task, 'Task generated by AI', 201);
});
